# escape sequence
# a way to modify inline string
# \n - new line
# \t - tab
# \r - remove the front part
# \b - backspace letter
# \\ - slash insertation
# \" - quotation 

religious_phrase = "To \rGod be the highest glory. \n \t\"A round\b of prayer \\is like a meditation filled with warmth.\""

print(religious_phrase)